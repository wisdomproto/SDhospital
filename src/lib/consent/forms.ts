export function getForm(code: string): ConsentForm | undefined {
  return CONSENT_FORMS.find((f) => f.code === code);
}

/** 본문의 {{key}} 를 발행 시 입력값으로 치환한다. 빈 값은 밑줄로 남긴다. */
export function renderBody(form: ConsentForm, fields: Record<string, string>): string {
  return form.body.replace(/\{\{(\w+)\}\}/g, (_, k: string) => {
    const v = (fields[k] ?? "").trim();
    return v || "________";
  });
}
