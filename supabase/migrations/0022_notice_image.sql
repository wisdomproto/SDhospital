-- 0022_notice_image.sql — 소식 이미지
--
-- 글만 있는 첫 화면은 삭막하다. 보호자 앱은 카톡·인스타와 비교당하는 자리다.
--
-- 파일을 올려 받지 않고 **주소만 저장한다**: 병원 홈페이지(sdamc.co.kr)에 이미 쓰는 이미지가 있고,
-- 같은 글을 앱에도 올리는 것이라 그 이미지를 그대로 가리키면 된다. 업로드 화면도, 저장 공간도 필요 없다.
-- ⚠️ 대신 홈페이지에서 그 이미지를 지우면 앱에서도 깨진다. 오래 걸어 둘 소식은 병원이 가진 주소를 쓸 것.

alter table notice add column if not exists image_url text;
